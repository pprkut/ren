# The release tarballs, in target/dist: ren-VERSION.tar.xz, the source of
# the commit checked out (git archive), and ren-VERSION-vendor.tar.xz, the
# crates of both workspaces (cargo vendor) with the cargo configuration
# that uses them, for building without the network (packages, the
# SlackBuild): unpacked into the source, `cargo build --offline` finds
# them.
#
#     scripts/dist.sh

set -euo pipefail
cd "$(dirname "$0")/.."

version=$(cargo metadata --format-version 1 --no-deps --locked \
    | python3 -c 'import json, sys; print(next(p["version"] for p in json.load(sys.stdin)["packages"] if p["name"] == "ren"))')
name=ren-$version
out=target/dist
mkdir -p "$out"

git archive --format=tar --prefix="$name/" HEAD | xz -T0 > "$out/$name.tar.xz"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/$name/.cargo"
# One directory for both workspaces; versions in the names, as the two
# lock files may want different versions of a crate.
cargo vendor --locked --versioned-dirs \
    --manifest-path Cargo.toml --sync crates/ren-servo/Cargo.toml \
    "$work/$name/vendor" > /dev/null
cat > "$work/$name/.cargo/config.toml" <<'CONFIG'
# Generated by scripts/dist.sh: the crates come from vendor/.
[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor"
CONFIG
# The Servo helper's own configuration sets its target directory; it
# takes the vendored crates from the parent directories' configuration.
tar -C "$work" -cf - "$name" | xz -T0 > "$out/$name-vendor.tar.xz"
ls -l "$out/$name.tar.xz" "$out/$name-vendor.tar.xz"
